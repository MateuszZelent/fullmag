#!/usr/bin/env python3
"""Regression check for the native CEED generated-file timestamp guard.

The fixture executes the production CMake helper in a temporary project with
``project(... NONE)``.  It never enables a language or compiles a C/C++ target.
"""

from __future__ import annotations

from pathlib import Path
import shutil
import subprocess
import tempfile
import time


ROOT = Path(__file__).resolve().parent


def require(condition: bool, message: str) -> None:
    if not condition:
        raise AssertionError(message)


def production_generator_function(cmake: str) -> str:
    start_marker = "function(fullmag_write_generated_file_if_different"
    end_marker = "\nendfunction()"
    start = cmake.find(start_marker)
    require(start >= 0, "production content-aware CMake helper is missing")
    end = cmake.find(end_marker, start)
    require(end >= 0, "production content-aware CMake helper has no endfunction")
    return cmake[start : end + len(end_marker)]


def assert_generated_call_sites(cmake: str) -> None:
    required_outputs = (
        "${CMAKE_CURRENT_BINARY_DIR}/generated/interface/ceed-windows-core.c",
        "${CMAKE_CURRENT_BINARY_DIR}/generated/interface/ceed-windows-jit-tools.c",
        "${CMAKE_CURRENT_BINARY_DIR}/generated/ceed/ceed.h",
        "${CEED_ADAPTER_MANIFEST}",
    )
    for output in required_outputs:
        guarded_call = (
            "fullmag_write_generated_file_if_different(\n"
            f'    "{output}"'
        )
        require(guarded_call in cmake, f"generated output is not behind the content-aware guard: {output}")
    for output in required_outputs[:3]:
        require(
            f'file(WRITE "{output}"' not in cmake,
            f"generated output still has an unconditional direct write: {output}",
        )


def configure(cmake: str, source: Path, build: Path, content: str | None = None) -> None:
    command = [cmake, "-S", str(source), "-B", str(build)]
    if content is not None:
        command.insert(1, f"-DFULLMAG_GUARD_CONTENT={content}")
    result = subprocess.run(command, text=True, capture_output=True, check=False)
    if result.returncode != 0:
        output = (result.stdout + "\n" + result.stderr).strip()
        raise AssertionError(f"isolated CMake configure failed ({result.returncode}):\n{output[-4000:]}")


def check_content_aware_generation() -> None:
    cmake_executable = shutil.which("cmake")
    require(cmake_executable is not None, "CMake is required for the project(NONE) regression fixture")
    production_cmake = (ROOT / "CMakeLists.txt").read_text(encoding="utf-8")
    assert_generated_call_sites(production_cmake)
    generator = production_generator_function(production_cmake)

    fixture_cmake = """cmake_minimum_required(VERSION 3.25)
project(fullmag_content_guard NONE)

{generator}

if(NOT DEFINED FULLMAG_GUARD_CONTENT)
    set(FULLMAG_GUARD_CONTENT "unchanged-content;with-semicolon")
endif()
fullmag_write_generated_file_if_different(
    "${{CMAKE_BINARY_DIR}}/generated-output.txt"
    "${{FULLMAG_GUARD_CONTENT}}")
""".format(generator=generator)

    with tempfile.TemporaryDirectory(prefix="fullmag-ceed-content-guard-") as temporary:
        temporary_root = Path(temporary)
        source = temporary_root / "source"
        build = temporary_root / "build"
        source.mkdir()
        (source / "CMakeLists.txt").write_text(fixture_cmake, encoding="utf-8", newline="\n")
        output = build / "generated-output.txt"

        configure(cmake_executable, source, build)
        initial_bytes = output.read_bytes()
        initial_mtime = output.stat().st_mtime_ns
        require(initial_bytes == b"unchanged-content;with-semicolon", "initial generated bytes are incorrect")

        time.sleep(1.1)
        configure(cmake_executable, source, build)
        unchanged_bytes = output.read_bytes()
        unchanged_mtime = output.stat().st_mtime_ns
        require(unchanged_bytes == initial_bytes, "identical configure changed generated bytes")
        require(
            unchanged_mtime == initial_mtime,
            "identical configure changed generated-file mtime",
        )

        time.sleep(1.1)
        configure(cmake_executable, source, build, content="changed-content;with-semicolon")
        changed_bytes = output.read_bytes()
        changed_mtime = output.stat().st_mtime_ns
        require(
            changed_bytes == b"changed-content;with-semicolon",
            "changed configure did not update generated bytes",
        )
        require(changed_mtime > unchanged_mtime, "changed configure did not update generated-file mtime")


def main() -> int:
    check_content_aware_generation()
    print("native CEED content-aware generation: PASS (project NONE; no compilation)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
