class SpinTransportAuthoringParameterParityTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
        cls.fixtures = build_parity_fixtures()

    def test_every_non_forbidden_manifest_path_is_represented_in_python_and_ir(self) -> None:
        for parameter in self.manifest["parameters"]:
            if parameter["round_trip"] == "forbidden":
                continue
            key = (parameter["family"], parameter["variant"])
            cases = self.fixtures.get(key)
            self.assertIsNotNone(cases, f"missing fixture for {key}")
            python_values = [
                value
                for item in cases or []
                for value in _path_values(item["python"], parameter["python_path"])
            ]
            ir_values = [
                value
                for item in cases or []
                for value in _path_values(item["ir"], parameter["ir_path"])
            ]
            self.assertTrue(
                python_values,
                f"{parameter['id']} missing from typed Python fixtures",
            )
            self.assertTrue(
                ir_values,
                f"{parameter['id']} missing from lowered IR fixtures",
            )

    def test_scene_document_round_trip_preserves_current_torque_and_oersted_contracts(self) -> None:
        current = build_parity_fixtures()[("current_transport", "ohmic_poisson")][0]["ir"]
        torques = [
            build_parity_fixtures()[("spin_torque", "zhang_li")][0]["ir"],
            build_parity_fixtures()[("spin_torque", "slonczewski")][0]["ir"],
            build_parity_fixtures()[("spin_torque", "prescribed_sot")][0]["ir"],
        ]
        oersted = [
            build_parity_fixtures()[("oersted", "oersted_cylinder")][0]["ir"],
            build_parity_fixtures()[("oersted", "oersted_field")][0]["ir"],
        ]
        builder = {
            "revision": 7,
            "geometries": [],
            "current_modules": [current],
            "spin_torques": torques,
            "oersted_terms": oersted,
        }
        scene = build_scene_document_from_builder(builder)
        inverse = build_builder_from_scene_document(scene)
        self.assertEqual(scene["current_transports"], [current])
        self.assertEqual(inverse["current_modules"], [current])
        self.assertEqual(inverse["spin_torques"], torques)
        self.assertEqual(inverse["oersted_terms"], oersted)


if __name__ == "__main__":
    unittest.main()
