def _path_values(root: object, path: str) -> list[object]:
    """Resolve a dotted manifest path over objects, mappings, and ``[*]`` lists."""

    tokens = [token for token in path.split(".") if token]

    def walk(value: object, remaining: list[str]) -> list[object]:
        if not remaining:
            return [value]
        token = remaining[0]
        match = re.fullmatch(r"([^\[]+)(?:\[\*\])?", token)
        if match is None:
            raise AssertionError(f"invalid parity path token {token!r}")
        name = match.group(1)
        wildcard = "[*]" in token
        if isinstance(value, Mapping):
            if name not in value:
                return []
            child = value[name]
        else:
            try:
                child = getattr(value, name)
            except AttributeError:
                # schema/constitutive versions are generated by ``to_ir`` and
                # are still public Python authoring semantics.
                to_ir = getattr(value, "to_ir", None)
                if not callable(to_ir):
                    to_ir = getattr(value, "to_ir_module", None)
                if not callable(to_ir):
                    return []
                generated = to_ir()
                if not isinstance(generated, Mapping) or name not in generated:
                    return []
                child = generated[name]
        if wildcard:
            if not isinstance(child, (list, tuple)):
                return []
            result: list[object] = []
            for item in child:
                result.extend(walk(item, remaining[1:]))
            return result
        return walk(child, remaining[1:])

    return walk(root, tokens)


def _region(object_id: str = "stack", region_id: str = "ferromagnet") -> fm.RegionRef:
    return fm.RegionRef(object_id, region_id)


def _surface(surface_id: str = "top") -> fm.SurfaceRef:
    return fm.SurfaceRef("stack", surface_id, (0.0, 0.0, 1.0))


