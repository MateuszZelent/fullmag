import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const appRoot = join(scriptDir, "..");
const generatedDir = join(appRoot, "src", "kernel", "api", "generated");
const openApiPath = join(generatedDir, "openapi-v2.json");
const clientOut = join(generatedDir, "openapi-v2-client.ts");
const pathsOut = join(generatedDir, "openapi-v2-paths.ts");

mkdirSync(generatedDir, { recursive: true });
const openApi = JSON.parse(readFileSync(openApiPath, "utf8"));
const paths = Object.keys(openApi.paths ?? {}).sort();

if (!paths.includes("/v2/sessions/current/status")) {
  throw new Error("OpenAPI v2 spec is missing /v2/sessions/current/status");
}

writeFileSync(
  clientOut,
  `/* This file was auto-generated by pnpm generate:api. Do not edit directly. */
import createClient from "openapi-fetch";
import type { paths } from "./openapi-v2-types";

export type OpenApiV2TransportOptions = Parameters<typeof createClient<paths>>[0];
export type OpenApiV2Transport = ReturnType<typeof createClient<paths>>;

export function createOpenApiV2Transport(options: OpenApiV2TransportOptions): OpenApiV2Transport {
  return createClient<paths>(options);
}
`,
);

writeFileSync(
  pathsOut,
  `/* This file was auto-generated by pnpm generate:api. Do not edit directly. */
export const openApiV2PathLiterals = ${JSON.stringify(paths, null, 2)} as const;

export type OpenApiV2Path = (typeof openApiV2PathLiterals)[number];

const openApiV2PathSet = new Set<string>(openApiV2PathLiterals);

export function openApiV2Path<P extends OpenApiV2Path>(path: P): P {
  return path;
}

export function assertOpenApiV2Path(path: string): asserts path is OpenApiV2Path {
  if (!openApiV2PathSet.has(path)) {
    throw new Error(\`Path is not present in generated OpenAPI v2: \${path}\`);
  }
}
`,
);
