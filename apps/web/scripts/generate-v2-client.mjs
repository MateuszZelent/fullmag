import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const generatedDir = join(process.cwd(), "src/api/generated");
const clientOut = join(generatedDir, "openapi-v2-client.ts");
const pathsOut = join(generatedDir, "openapi-v2-paths.ts");
const specPath = join(generatedDir, "openapi-v2.json");
mkdirSync(generatedDir, { recursive: true });

writeFileSync(
  clientOut,
  `/* This file was auto-generated by npm run generate:api. Do not edit directly. */\n` +
    `import createClient from "openapi-fetch";\n` +
    `import type { paths } from "./openapi-v2-types";\n\n` +
    `export type OpenApiV2TransportOptions = Parameters<typeof createClient<paths>>[0];\n` +
    `export type OpenApiV2Transport = ReturnType<typeof createClient<paths>>;\n\n` +
    `export function createOpenApiV2Transport(options: OpenApiV2TransportOptions): OpenApiV2Transport {\n` +
    `  return createClient<paths>(options);\n` +
    `}\n`,
);

const spec = JSON.parse(readFileSync(specPath, "utf8"));
const paths = Object.keys(spec.paths ?? {}).sort();
const body =
  `/* This file was auto-generated by npm run generate:api. Do not edit directly. */\n` +
  `export const openApiV2PathLiterals = ${JSON.stringify(paths, null, 2)} as const;\n\n` +
  `export type OpenApiV2Path = (typeof openApiV2PathLiterals)[number];\n\n` +
  `const openApiV2PathSet = new Set<string>(openApiV2PathLiterals);\n\n` +
  `export function openApiV2Path<P extends OpenApiV2Path>(path: P): P {\n` +
  `  return path;\n` +
  `}\n\n` +
  `export function assertOpenApiV2Path(path: string): asserts path is OpenApiV2Path {\n` +
  `  if (!openApiV2PathSet.has(path)) {\n` +
  `    throw new Error(\`Path is not present in generated OpenAPI v2: \${path}\`);\n` +
  `  }\n` +
  `}\n`;

writeFileSync(pathsOut, body);
